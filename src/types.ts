/** Тип представления календаря: правая боковая панель. */
export const VIEW_TYPE_TASK_CALENDAR = 'task-calendar';

/** Тип представления списка задач: вкладка в основной области. */
export const VIEW_TYPE_TASK_LIST = 'task-calendar-list';

/**
 * Источник событий hover-link: под ним плагин представлен в «Предпросмотре
 * страницы». Совпадает с прежним типом календаря - менять его незачем.
 */
export const HOVER_LINK_SOURCE = 'task-calendar';

export type TaskCalendarSettings = {
	/**
	 * Папка, в которую кладутся задачи, созданные из списка. '/' - корень
	 * хранилища. На поиск задач не влияет: сканируется всё хранилище.
	 *
	 * Имя ключа осталось с тех пор, когда папка ограничивала и скан: так значение
	 * из data.json подхватывается без миграции.
	 */
	tasksFolderPath: string;
	/**
	 * Свитч «Календарь в списке». Календарь сверху списка всегда; выключен (по
	 * умолчанию) - день в календаре выбирается, под ним задачи выбранного дня, как
	 * до версии 1.0.1; включён - день не выбирается, под календарём 100 ближайших
	 * невыполненных задач (просьба пользователя 14.11.2026). Имя ключа осталось
	 * прежним, чтобы значение из data.json подхватилось без миграции.
	 */
	calendarInList: boolean;
	/**
	 * Группа «Выполнено» под списком со свитчем свёрнута (просьба пользователя
	 * 14.11.2026). Хранится здесь, чтобы пережить перезапуск; в настройках
	 * переключателя нет - сворачивают заголовком группы.
	 */
	doneCollapsed: boolean;
};

export const DEFAULT_SETTINGS: TaskCalendarSettings = {
	tasksFolderPath: '/',
	calendarInList: false,
	doneCollapsed: false,
};
